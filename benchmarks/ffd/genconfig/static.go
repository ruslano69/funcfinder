package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// generateD resolves JSON at build time and emits immutable D data. Unsupported
// schema additions fail here instead of being silently dropped by a runtime reader.
func generateD() ([]byte, error) {
	raw, err := generate()
	if err != nil {
		return nil, err
	}
	var value any
	if err := json.Unmarshal(raw, &value); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Generated by genconfig -d; do not edit.\nmodule ffd_config_data;\n\nimport ffd_config_table;\n\nimmutable ConfigEntry configRoot = ")
	if err := emitD(&b, "", value, 0); err != nil {
		return nil, err
	}
	b.WriteString(";")
	return b.Bytes(), nil
}

func emitD(b *bytes.Buffer, key string, value any, depth int) error {
	quote := strconv.QuoteToASCII
	fmt.Fprintf(b, "ConfigEntry(%s, ConfigKind.", quote(key))
	switch v := value.(type) {
	case nil:
		b.WriteString("null_)")
	case string:
		fmt.Fprintf(b, "text, %s)", quote(v))
	case bool:
		fmt.Fprintf(b, "flag, \"\", %t)", v)
	case []any:
		b.WriteString("strings, \"\", false, [")
		for i, item := range v {
			s, ok := item.(string)
			if !ok {
				return fmt.Errorf("%s: expected string array, got %T", key, item)
			}
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(quote(s))
		}
		b.WriteString("])")
	case map[string]any:
		b.WriteString("object_, \"\", false, null, [\n")
		keys := make([]string, 0, len(v))
		for k := range v {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			b.WriteString(strings.Repeat("    ", depth+1))
			if err := emitD(b, k, v[k], depth+1); err != nil {
				return err
			}
			b.WriteString(",\n")
		}
		b.WriteString(strings.Repeat("    ", depth) + "])")
	default:
		return fmt.Errorf("%s: unsupported configuration value %T", key, value)
	}
	return nil
}
